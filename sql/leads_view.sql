-- MARKETING_REPORTS.PUBLIC.LEADS — daily lead-funnel counts per studio + source.
-- Read by fetch_data.py. Not deployed automatically: run this in Snowflake.
--
-- Booking columns are dated by FIRST_BOOKING_DATE (dates only, no times).
-- BOOKINGS_ATTENDED = first bookings whose lead has a FIRST_VISIT_DATE, so
-- BOOKINGS_ATTENDED / FIRST_BOOKINGS is a cohort booked → attended rate.

CREATE OR REPLACE VIEW MARKETING_REPORTS.PUBLIC.LEADS (
    EVENT_DATE,
    STUDIO_ID,
    STUDIO_NAME,
    SOURCE,
    SIGNUPS,
    FIRST_VISITS,
    FIRST_ACTIVATIONS,
    FIRST_SALES,
    FIRST_BOOKINGS,
    SAME_DAY_BOOKINGS,
    NEXT_DAY_BOOKINGS,
    BOOKINGS_WITHIN_7_DAYS,
    BOOKINGS_AFTER_7_DAYS,
    BOOKINGS_ATTENDED
) AS

WITH events AS (
    SELECT
        SIGNUP_DATE AS EVENT_DATE,
        STUDIO_ID, STUDIO_NAME, SOURCE,
        'signup' AS METRIC,
        0 AS SAME_DAY,
        0 AS NEXT_DAY,
        0 AS WITHIN_7_DAYS,
        0 AS AFTER_7_DAYS,
        0 AS ATTENDED
    FROM MARKETING_REPORTS.PUBLIC.LEADS_LIST
    WHERE SIGNUP_DATE IS NOT NULL

    UNION ALL

    SELECT
        FIRST_VISIT_DATE,
        STUDIO_ID, STUDIO_NAME, SOURCE,
        'first_visit', 0, 0, 0, 0, 0
    FROM MARKETING_REPORTS.PUBLIC.LEADS_LIST
    WHERE FIRST_VISIT_DATE IS NOT NULL

    UNION ALL

    SELECT
        FIRST_MEMBERSHIP_ACTIVATION_DATE,
        STUDIO_ID, STUDIO_NAME, SOURCE,
        'first_activation', 0, 0, 0, 0, 0
    FROM MARKETING_REPORTS.PUBLIC.LEADS_LIST
    WHERE FIRST_MEMBERSHIP_ACTIVATION_DATE IS NOT NULL

    UNION ALL

    SELECT
        FIRST_SALE_DATE,
        STUDIO_ID, STUDIO_NAME, SOURCE,
        'first_sale', 0, 0, 0, 0, 0
    FROM MARKETING_REPORTS.PUBLIC.LEADS_LIST
    WHERE FIRST_SALE_DATE IS NOT NULL
      AND FIRST_MEMBERSHIP_ACTIVATION_DATE IS NOT NULL

    UNION ALL

    SELECT
        FIRST_BOOKING_DATE,
        STUDIO_ID, STUDIO_NAME, SOURCE,
        'first_booking',
        SAME_DAY_BOOKINGS,
        NEXT_DAY_BOOKINGS,
        BOOKINGS_WITHIN_7_DAYS,
        BOOKINGS_AFTER_7_DAYS,
        IFF(FIRST_VISIT_DATE IS NOT NULL, 1, 0)
    FROM MARKETING_REPORTS.PUBLIC.LEADS_LIST
    WHERE FIRST_BOOKINGS = 1
)

SELECT
    EVENT_DATE,
    STUDIO_ID,
    STUDIO_NAME,
    SOURCE,

    SUM(IFF(METRIC = 'signup', 1, 0)) AS SIGNUPS,
    SUM(IFF(METRIC = 'first_visit', 1, 0)) AS FIRST_VISITS,
    SUM(IFF(METRIC = 'first_activation', 1, 0)) AS FIRST_ACTIVATIONS,
    SUM(IFF(METRIC = 'first_sale', 1, 0)) AS FIRST_SALES,
    SUM(IFF(METRIC = 'first_booking', 1, 0)) AS FIRST_BOOKINGS,

    SUM(SAME_DAY) AS SAME_DAY_BOOKINGS,
    SUM(NEXT_DAY) AS NEXT_DAY_BOOKINGS,
    SUM(WITHIN_7_DAYS) AS BOOKINGS_WITHIN_7_DAYS,
    SUM(AFTER_7_DAYS) AS BOOKINGS_AFTER_7_DAYS,
    SUM(ATTENDED) AS BOOKINGS_ATTENDED

FROM events
GROUP BY
    EVENT_DATE,
    STUDIO_ID,
    STUDIO_NAME,
    SOURCE;
